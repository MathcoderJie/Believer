using Believer.BelieverCode.Keywords;
using MegaCrit.Sts2.Core.Entities.Cards;
using MegaCrit.Sts2.Core.Entities.Creatures;
using MegaCrit.Sts2.Core.Models;
using MegaCrit.Sts2.Core.Rooms;

namespace Believer.BelieverCode.Cards.Miracles;

/// <summary>
/// Shared classification helpers for the 12 formal 神迹 / Miracles (M6).
///
/// A card is a Miracle when it carries the stable <see cref="BelieverKeywords.Miracle"/> keyword, not
/// merely because of its name or class. Enhanced Omniscience copies add the separate
/// <see cref="BelieverKeywords.EnhancedMiracle"/> keyword. A temporary copy is identified by the
/// engine's own <c>CloneOf</c> marker.
/// </summary>
public static class MiracleRules
{
    /// <summary>True for any card carrying the stable Miracle keyword (normal or enhanced).</summary>
    public static bool IsMiracle(CardModel? card)
        => card != null && card.Keywords.Contains(BelieverKeywords.Miracle);

    /// <summary>True for a temporary enhanced Miracle generated by Omniscience.</summary>
    public static bool IsEnhancedMiracle(CardModel? card)
        => card != null && card.Keywords.Contains(BelieverKeywords.EnhancedMiracle);

    /// <summary>True for a temporary copy (clone) such as the copies created by 五饼二鱼.</summary>
    public static bool IsTemporaryCopy(CardModel? card) => card != null && card.CloneOf != null;

    /// <summary>
    /// True for an ordinary card: neither a Miracle nor a temporary copy. This is what 五饼二鱼,
    /// 拉撒复生 and 万军降临 are allowed to interact with.
    /// </summary>
    public static bool IsOrdinaryCard(CardModel? card)
        => card != null && !card.Keywords.Contains(BelieverKeywords.Miracle) && card.CloneOf == null;

    /// <summary>
    /// True when the enemy belongs to a boss encounter. The base game has no per-monster boss flag
    /// (MonsterModel exposes no such member), so this uses the encounter's <see cref="RoomType"/>.
    /// </summary>
    public static bool IsBossEnemy(Creature? creature)
        => creature?.Monster != null && creature.CombatState?.Encounter?.RoomType == RoomType.Boss;
}
