using Believer.BelieverCode.Miracles;
using MegaCrit.Sts2.Core.Entities.Cards;
using MegaCrit.Sts2.Core.Entities.Creatures;
using MegaCrit.Sts2.Core.Models;
using MegaCrit.Sts2.Core.Rooms;

namespace Believer.BelieverCode.Cards.Miracles;

/// <summary>
/// Shared classification helpers for the 12 formal 神迹 / Miracles (M6).
///
/// Everything here is derived from real game API: a card is a Miracle when it derives from
/// <see cref="MiracleCard"/>; a temporary copy is a card with a non-null <c>CloneOf</c> (the engine's
/// own clone marker, set by <c>CardModel.CreateClone</c>); the base game has no per-monster "boss"
/// flag, so an enemy is treated as a boss when its combat encounter is a <see cref="RoomType.Boss"/>
/// encounter.
/// </summary>
public static class MiracleRules
{
    /// <summary>True for a 神迹 card (temporary, generated by Omniscience).</summary>
    public static bool IsMiracle(CardModel? card) => card is MiracleCard;

    /// <summary>True for a temporary copy (clone) such as the copies created by 五饼二鱼.</summary>
    public static bool IsTemporaryCopy(CardModel? card) => card != null && card.CloneOf != null;

    /// <summary>
    /// True for an ordinary card: neither a 神迹 nor a temporary copy. This is what 五饼二鱼,
    /// 拉撒复生 and 万军降临 are allowed to interact with.
    /// </summary>
    public static bool IsOrdinaryCard(CardModel? card)
        => card != null && card is not MiracleCard && card.CloneOf == null;

    /// <summary>
    /// True when the enemy belongs to a boss encounter. The base game has no per-monster boss flag
    /// (MonsterModel exposes no such member), so this uses the encounter's <see cref="RoomType"/>.
    /// </summary>
    public static bool IsBossEnemy(Creature? creature)
        => creature?.Monster != null && creature.CombatState?.Encounter?.RoomType == RoomType.Boss;
}
